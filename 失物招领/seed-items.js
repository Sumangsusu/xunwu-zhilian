const removed = db.prepare('DELETE FROM items WHERE publisher = ?').run(SEED_TAG).changes;

const now = Date.now();
const dayMs = 86400000;
const stmt = db.prepare(`
  INSERT INTO items (type, title, category, color, location, date, image, description,
    contact, reward, features, publisher, status, quiz, map_x, map_y, created_at)
  VALUES (@type, @title, @category, @color, @location, @date, @image, @description,
    @contact, @reward, @features, @publisher, 'active', @quiz, @map_x, @map_y, @created_at)
`);

const run = db.transaction((rows) => {
  rows.forEach((r, i) => {
    const [type, title, category, color, location, description, reward, features, quiz] = r;
    const coord = coordFor(location);
    stmt.run({
      type, title, category, color, location, description, reward,
      date: new Date(Date.UTC(2026, 10, 23) - i * 2 * dayMs).toISOString().slice(0, 10),
      image: ROW_IMAGES[i],
      contact: `演示联系 TEST-${1000 + i}`,
      features: JSON.stringify(features),
      publisher: SEED_TAG,
      quiz: JSON.stringify(quiz || []),
      map_x: coord.mapX,
      map_y: coord.mapY,
      created_at: now - i * 1000
    });
  });
});
