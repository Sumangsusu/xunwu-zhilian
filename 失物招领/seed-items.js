function coordFor(location) {
  const zone = ZONES.find(([name]) => location.includes(name)) ||
    ZONES[Math.floor(Math.random() * ZONES.length)];
  const [, x, y, w, h] = zone;
  return {
    mapX: Math.round(x + w * (0.2 + Math.random() * 0.6)),
    mapY: Math.round(y + h * (0.2 + Math.random() * 0.6))
  };
}

